# -*- coding: utf-8 -*-
"""
gutenberg_data.py

Loads, cleans, and chunks the raw Project Gutenberg book HTML files that
train_vades.py trains the VADES style model on. This is the SAME corpus that
ends up in the FAISS "database" the recommender queries — one pass over the
books produces both the trained model and the retrieval index.

Expected on-disk layout (unchanged from the original notebook):
    BOOKS_DIR/
        <author_1>/
            some_book.html
            another_book.html
        <author_2>/
            ...

book_id is built the same way as in the original vades_main.py:
    book_id = f"{author}___{file_name}"

HTML cleaning
-------------
Modern Project Gutenberg HTML (generated by "Ebookmaker" — this is what
produced pg11870-images.html, the sample you shared) wraps ALL of its
boilerplate — the license blurb, the machine-readable Title/Author/Release
date/Language/Credits block, and the START/END markers — inside
<section id="pg-header">...</section> and
<section id="pg-footer">...</section> (both also carry class="pg-boilerplate").

The original notebook's clean_gutenberg_text only ran regex over the
flattened text AFTER extraction, which does NOT catch that whole pg-header
block: the license blurb and the Title/Author/Release date/Credits metadata
survive as noise prepended to the first chunk of every book (verified this
by running the original regex pipeline against your actual file — see
test_cleaning.py). extract_text_from_html here instead removes those
<section> elements directly from the HTML tree BEFORE flattening to text,
which is both more reliable and matches the real structure of your sample
file exactly. clean_gutenberg_text still runs afterwards as a second-pass
regex cleanup — belt and suspenders for anything the structural removal
missed, and the only cleaning that happens at all for older Gutenberg HTML
that doesn't use these semantic id wrappers.

Checkpointing
-------------
load_or_build_chunks_df processes one book at a time and saves progress
every `checkpoint_every` books (default 10) to a partial checkpoint file, so
if the process is interrupted partway through a large corpus, re-running it
resumes from where it left off instead of re-cleaning everything already done.
"""

import os
import re

import pandas as pd
from bs4 import BeautifulSoup
from sklearn.model_selection import train_test_split
from tqdm import tqdm

from checkpointing import save_partial, load_partial, clear_partial

# Boilerplate wrappers used by current ("Ebookmaker") Gutenberg HTML exports.
PG_BOILERPLATE_IDS = ("pg-header", "pg-footer")
PG_BOILERPLATE_CLASS = "pg-boilerplate"


def extract_text_from_html(path: str) -> str:
    """
    Extracts body text from a Gutenberg HTML file, stripping the standard
    Project Gutenberg header/footer boilerplate BEFORE flattening to plain
    text (see module docstring for why this beats regexing it out afterwards).
    """
    with open(path, "r", encoding="utf-8", errors="ignore") as f:
        soup = BeautifulSoup(f, "html.parser")

    # "head" too: otherwise the <title> ("X, by Author") is prepended to the
    # first chunk of every book.
    for tag in soup(["head", "table", "script", "style"]):
        tag.extract()

    # Structural removal: current Gutenberg HTML wraps the ENTIRE license
    # text, machine-readable metadata block, and START/END markers in these
    # elements — removing them here strips all of it in one shot, rather
    # than chasing fragments of it with regex after the fact.
    for boilerplate_id in PG_BOILERPLATE_IDS:
        el = soup.find(id=boilerplate_id)
        if el is not None:
            el.extract()
    for el in soup.find_all(class_=PG_BOILERPLATE_CLASS):
        el.extract()

    # "\n" (not " ") between text nodes so line-oriented cleanup in
    # clean_gutenberg_text (e.g. the "Produced by ..." credit line) has a line
    # end to stop at. clean_gutenberg_text collapses all whitespace at the end,
    # so the final text is unchanged by this choice.
    return soup.get_text(separator="\n", strip=True)


def clean_gutenberg_text(text: str) -> str:
    """
    Second-pass regex cleanup, run after extract_text_from_html's structural
    removal. Unchanged in spirit from the original notebook's version, with
    a couple of added patterns ("THIS" as well as "THE") for older Gutenberg
    wording variants. For files where the structural removal above already
    caught everything, this mostly just tidies whitespace and stray
    "CHAPTER"/markdown-style separators inside the body text.
    """
    # \A anchor: without it, when the phrase is absent (the normal case once
    # extract_text_from_html has removed pg-header) the regex engine retries
    # the lazy .*? from every start position -> O(n^2), ~hours per real book.
    # Matches are identical, since any match would start at position 0 anyway.
    text = re.sub(r'(?is)\A.*?(the project gutenberg ebook of )', '', text, count=1)
    # Drop everything up to and including the START marker, not just the marker
    # itself: in older Gutenberg files (no pg-header <section>) the license
    # blurb and Title/Author/Release Date block sit *before* this marker.
    # \A-anchored for the same linear-time reason as the line above.
    text = re.sub(r'(?is)\A.*?\*\*\*\s*start of (the|this) project gutenberg ebook.*?\*\*\*', '',
                   text, count=1)
    text = re.sub(r'(?is)end of (the|this) project gutenberg ebook.*', '', text)
    text = re.sub(r'(?is)\*\*\*.*?project gutenberg.*?\*\*\*', '', text)
    # Credit line only where it actually appears in older files: right at the
    # start, after the header/START marker removal above. Unanchored, this
    # deleted ordinary prose (e.g. "...produced by velvet wrapping, the
    # crystal did" in The Crystal Egg, pg11870).
    text = re.sub(r'(?i)\A\s*(produced by|transcribed from)[^\n]*', '', text)
    text = re.sub(r'\b(CHAPTER|Chapter)\s+[A-Z0-9IVX]+\b', '', text)
    text = re.sub(r'[_*#~-]{2,}', ' ', text)
    text = re.sub(r'http\S+', '', text)
    return re.sub(r'\s+', ' ', text).strip()


def chunk_text(text: str, size: int = 4000, overlap: int = 500):
    chunks, start = [], 0
    while start < len(text):
        chunks.append(text[start:start + size])
        start += size - overlap
    return chunks


def load_or_build_chunks_df(books_dir: str, output_csv: str,
                             checkpoint_every: int = 10) -> pd.DataFrame:
    """
    Walks books_dir/<author>/*.html, cleans + chunks each book, and returns a
    DataFrame with columns: author, file_name, text, book_id.

    Checkpointed: saves progress every `checkpoint_every` books to
    "<output_csv>.partial.joblib". If that file exists on the next run, it
    resumes from there instead of reprocessing already-done books. Cleared
    automatically once the final output_csv is written — delete output_csv
    (and any leftover .partial.joblib next to it) to force a full rebuild.
    """
    if os.path.exists(output_csv):
        print(f"Loading cached chunk dataset from {output_csv}")
        df = pd.read_csv(output_csv)
        if "book_id" not in df.columns:
            df["book_id"] = df["author"] + "___" + df["file_name"]
        return df

    if not os.path.isdir(books_dir):
        raise FileNotFoundError(
            f"books_dir '{books_dir}' does not exist. Expected <books_dir>/<author>/*.html"
        )

    authors = [a for a in os.listdir(books_dir) if os.path.isdir(os.path.join(books_dir, a))]
    if not authors:
        raise ValueError(
            f"No author subfolders found under '{books_dir}'. Expected one folder per "
            f"author, each containing that author's .html book files."
        )

    # Build the full list of (author, file_name) tasks up front so resuming
    # can just skip whichever ones are already marked done.
    book_tasks = []
    for author in sorted(authors):
        folder = os.path.join(books_dir, author)
        for fname in sorted(os.listdir(folder)):
            if fname.lower().endswith(".html"):
                book_tasks.append((author, fname))
    if not book_tasks:
        raise ValueError(f"No .html files found under '{books_dir}'.")

    ckpt_path = output_csv + ".partial.joblib"
    state = load_partial(ckpt_path)
    if state is not None:
        data = state["data"]
        done = set(state["done"])
        print(f"Resuming from checkpoint: {len(done)}/{len(book_tasks)} books already processed")
    else:
        data, done = [], set()

    since_checkpoint = 0
    for author, fname in tqdm(book_tasks, desc="Books"):
        key = f"{author}___{fname}"
        if key in done:
            continue
        try:
            raw = extract_text_from_html(os.path.join(books_dir, author, fname))
            clean = clean_gutenberg_text(raw)
            for chunk in chunk_text(clean):
                if chunk.strip():
                    data.append({"author": author, "file_name": fname, "text": chunk})
        except Exception as e:
            print(f"  skipped {author}/{fname}: {e}")
        done.add(key)
        since_checkpoint += 1

        if since_checkpoint >= checkpoint_every:
            save_partial(ckpt_path, {"data": data, "done": list(done)})
            since_checkpoint = 0

    if not data:
        raise ValueError(f"No usable text extracted from any .html file under '{books_dir}'.")

    df = pd.DataFrame(data)
    df["book_id"] = df["author"] + "___" + df["file_name"]
    os.makedirs(os.path.dirname(output_csv) or ".", exist_ok=True)
    df.to_csv(output_csv, index=False)
    clear_partial(ckpt_path)   # finished — no need to keep the partial around
    print(f"Built {len(df)} chunks from {df['book_id'].nunique()} books, "
          f"{df['author'].nunique()} authors")
    return df


def book_level_split(df: pd.DataFrame, split_dir: str, test_size: float = 0.3,
                      val_fraction_of_temp: float = 0.5, random_state: int = 42):
    """
    Splits by BOOK (not chunk) so no book's chunks appear in more than one
    split — a chunk-level split would leak the same book's style signature
    across train/val/test and inflate every downstream metric.

    Already checkpointed by nature: the three split CSVs ARE the checkpoint —
    a re-run with the same split_dir loads them back instead of re-splitting.
    """
    train_csv, val_csv, test_csv = [os.path.join(split_dir, f"{s}.csv") for s in ["train", "val", "test"]]

    if all(os.path.exists(f) for f in [train_csv, val_csv, test_csv]):
        print(f"Loading cached splits from {split_dir}")
        return (pd.read_csv(train_csv), pd.read_csv(val_csv), pd.read_csv(test_csv))

    books = df[["author", "book_id"]].drop_duplicates()
    counts = books["author"].value_counts()
    # Stratifying twice (train/temp, then val/test within temp) needs each
    # author's book count to survive both splits with >=2 books left for the
    # second stratification.
    min_required = int(-(-2 // test_size))  # ceil(2 / test_size)
    if (counts < min_required).any():
        thin = counts[counts < min_required].to_dict()
        raise ValueError(
            f"book_level_split stratifies by author twice (train/temp, then val/test "
            f"within temp), which needs at least {min_required} books per author at "
            f"test_size={test_size}. These authors have too few books: {thin}. Either "
            f"add more books for them, drop them, or raise test_size / lower the "
            f"per-author minimum by accepting a non-stratified split instead."
        )

    train_books, temp = train_test_split(books, test_size=test_size,
                                          stratify=books["author"], random_state=random_state)
    val_books, test_books = train_test_split(temp, test_size=val_fraction_of_temp,
                                              stratify=temp["author"], random_state=random_state)

    train_df = df[df["book_id"].isin(train_books["book_id"])].reset_index(drop=True)
    val_df = df[df["book_id"].isin(val_books["book_id"])].reset_index(drop=True)
    test_df = df[df["book_id"].isin(test_books["book_id"])].reset_index(drop=True)

    assert len(set(train_df["book_id"]) & set(test_df["book_id"])) == 0
    assert len(set(train_df["book_id"]) & set(val_df["book_id"])) == 0
    assert len(set(val_df["book_id"]) & set(test_df["book_id"])) == 0

    os.makedirs(split_dir, exist_ok=True)
    train_df.to_csv(train_csv, index=False)
    val_df.to_csv(val_csv, index=False)
    test_df.to_csv(test_csv, index=False)

    print(f"Train: {len(train_df)}, Val: {len(val_df)}, Test: {len(test_df)} chunks")
    return train_df, val_df, test_df
